/** Anything that can land on the aggregated calendar. */
export type AgendaKind = "event" | "entry";

export interface AgendaItem {
  id: string;
  kind: AgendaKind;
  title: string;
  subtitle?: string | null;
  /** Local `YYYY-MM-DD` the item belongs to. */
  day: string;
  /** Null for all-day items. */
  start: Date | null;
  end: Date | null;
  memberIds: string[];
  allDay?: boolean;
  /** Imported from a calendar feed — deleting it here would just resync back. */
  readOnly?: boolean;

  /*
   * Everything below exists only for the detail sheet. The agenda row is a
   * one-line summary and deliberately shows none of it — but a row that can be
   * opened has to carry what opening it reveals, and the alternative (looking
   * the source row back up by id) would mean the sheet re-deriving the join
   * `buildAgenda` already did.
   */

  /** Entries only. `general` is treated as "uncategorised" and not shown. */
  category?: string | null;
  /** Events only. */
  location?: string | null;
  /** Events only — never surfaced anywhere in the UI before the detail sheet. */
  description?: string | null;
}

/**
 * One chore, ticked off for one period. The chore itself is defined in
 * `lib/chores.ts` — this row only records that it happened, so the roster can
 * be reworded without touching history.
 *
 * `period_key` is a local day (`2026-08-24`) for daily chores and an ISO week
 * (`2026-W35`) for weekly ones. Which of the two a chore uses comes from its
 * cadence, so the key is derived on the client rather than stored per row.
 */
export interface ChoreTick {
  chore_key: string;
  period_key: string;
  done_by: string | null;
  done_at: string;
}

