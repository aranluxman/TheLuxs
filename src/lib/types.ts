/**
 * Which thread is on screen: `null` is the group, a member id is a one-to-one
 * conversation with that person.
 *
 * These are *not* private in the security sense. There is no login, so the
 * filtering is a query the client asks for rather than a rule the database
 * enforces — see the Security model section of the README, and the header of
 * migration 0006.
 */
export type ConversationId = string | null;

/** The group thread needs a name to be used as a Record key. */
export const GROUP_CONVERSATION = "group";

/**
 * Names the thread a message belongs to, for cache and read-mark bookkeeping.
 *
 * For a DM this is the database's `conversation_key`: the two ids sorted and
 * joined, so both directions agree. The sort must match migration 0006's
 * generated column exactly or a thread reads as empty — 0006 compares as
 * `uuid`, which is byte order, and Supabase hands out canonical lowercase
 * UUIDs, so a plain JS compare over two equal-length strings of [0-9a-f-]
 * gives the same answer without a collation in sight.
 */
export function conversationKeyFor(
  senderId: string,
  recipientId: string | null,
): string {
  if (!recipientId) return GROUP_CONVERSATION;
  return senderId < recipientId
    ? `${senderId}:${recipientId}`
    : `${recipientId}:${senderId}`;
}

